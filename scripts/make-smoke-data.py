"""Create a reproducible, synthetic-only training and trajectory fixture."""

import argparse
import csv
import math
from pathlib import Path

import cv2

from kxvo.geometry import rot_to_euler, wrap_pi
from kxvo.synth import Room, default_camera, simulate
from kxvo.train import motion_blur
from kxvo.video import Recorder


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--width", type=int, default=320)
    parser.add_argument("--scene-seed", type=int, default=12)
    parser.add_argument("--sensor-seed", type=int, default=8)
    args = parser.parse_args()
    root = args.output
    root.mkdir(parents=True, exist_ok=False)
    camera = default_camera().scaled(args.width)
    camera.save(root / "camera.json")
    with (root / "manifest.csv").open("x", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["path", "split", "group", "rights"])
        for split, seed in (("train", 1), ("validation", 2)):
            for n, sample in enumerate(simulate(duration=1, fps=4, seed=seed, room=Room(seed=7))):
                filename = f"{split}-{n}.png"
                cv2.imwrite(str(root / filename), sample.image)
                writer.writerow([filename, split, split, "Generated by kxvo synthetic renderer"])
    # Deliberately use a different room seed for the held-out trajectory fixture.
    for degraded in (False, True):
        run = Recorder(root / ("blur" if degraded else "clean"))
        last_yaw = None
        try:
            for sample in simulate(duration=24, cam=camera, room=Room(seed=args.scene_seed),
                                   seed=args.sensor_seed):
                yaw = rot_to_euler(sample.R_WB)[2]
                image = sample.image
                if degraded and last_yaw is not None and 6 <= sample.t % 8 < 7:
                    length = math.ceil(camera.fx * abs(wrap_pi(yaw - last_yaw)) * 0.9)
                    image = motion_blur(image, min(25, max(length, 7)), 0)
                run.write(sample.t, image, {"att": sample.att_meas, "range_m": sample.range_m,
                                          "truth_p": sample.p_WB.tolist(), "truth_rpy": rot_to_euler(sample.R_WB)})
                last_yaw = yaw
        finally:
            run.close()


if __name__ == "__main__":
    main()
